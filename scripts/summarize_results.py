#!/usr/bin/env python3
"""Collect the real results of the project into results/RESULTS.md.

Reads whatever exists of:
    results/cavity_mesh_study.csv, results/cavity_gci.json,
    results/sweep_results.csv,     results/transient_results.csv, results/surrogate_metrics.json
and writes markdown tables that I copy into the README.

I only quote numbers that this script reads from files the other scripts wrote.
If an input is missing it prints "not available" instead of a guess, so I cannot
publish a number I did not actually compute.
"""
import json
from pathlib import Path

import pandas as pd

R = Path(__file__).resolve().parents[1] / "results"


def load_json(name):
    f = R / name
    return json.loads(f.read_text()) if f.exists() else None


def main():
    out = ["# Results (generated by scripts/summarize_results.py)\n"]

    f = R / "cavity_mesh_study.csv"
    if f.exists():
        df = pd.read_csv(f)
        out += ["## Cavity, Ra = 1e5: hot-wall Nusselt number vs de Vahl Davis (1983)\n",
                "| N | cells | Nu | error vs reference [%] |", "|---|---|---|---|"]
        out += [f"| {int(r.N)} | {int(r.cells_2d)} | {r.Nu:.4f} | {r.error_pct:+.2f} |"
                for r in df.itertuples()]
        g = load_json("cavity_gci.json")
        if g:
            out.append(f"\nApparent order p = {g['p']:.2f}, extrapolated Nu = {g['f_ext']:.4f}, "
                       f"GCI(fine) = {g['gci_fine_pct']:.2f} %, monotonic convergence: {g['monotonic']}.")
        out.append(f"\nFinest-mesh error: {df.iloc[-1].error_pct:+.2f} %.\n")
    else:
        out.append("## Cavity\nnot available (run `./run_all.sh cavity`)\n")

    f = R / "sweep_results.csv"
    if f.exists():
        df = pd.read_csv(f)
        out.append("## Cabinet sweep\n")
        c = df[df["converged"] == True]  # I quote ranges of converged cases only: the others are not reliable
        out.append(f"{len(df)} cases, converged flag true for {len(c)}. "
                   f"Converged cases: T_max range {c['T_max_K'].min():.1f} to {c['T_max_K'].max():.1f} K, "
                   f"dp range {c['dp_Pa'].min():.3f} to {c['dp_Pa'].max():.3f} Pa.\n")
        f2 = R / "transient_results.csv"
        if f2.exists():
            tr = pd.read_csv(f2)
            out += ["### Unconverged cases re-run transient (buoyantPimpleFoam)\n",
                    "| case | T_max steady [K] | T_max mean [K] | std [K] | dp steady [Pa] | dp mean [Pa] | flow time [s] |",
                    "|---|---|---|---|---|---|---|"]
            out += [f"| {r.case} | {r.T_max_steady_K:.1f} | {r.T_max_mean_K:.1f} | {r.T_max_std_K:.1f} "
                    f"| {r.dp_steady_Pa:.3f} | {r.dp_mean_Pa:.3f} | {r.flow_time_s:.0f} |" for r in tr.itertuples()]
            out.append("")
    else:
        out.append("## Cabinet sweep\nnot available (run `./run_all.sh cabinet`)\n")

    m = load_json("surrogate_metrics.json")
    if m:
        out += ["## Surrogate (MLP)\n",
                "| target | R2 hold-out | MAE hold-out | R2 LOO | MAE LOO |", "|---|---|---|---|---|",
                f"| T_max rise [K] | {m['holdout_R2_dT_max_K']:.4f} | {m['holdout_MAE_dT_max_K']:.3f} "
                f"| {m['loo_R2_dT_max_K']:.4f} | {m['loo_MAE_dT_max_K']:.3f} |",
                f"| dp [Pa] | {m['holdout_R2_dp_Pa']:.4f} | {m['holdout_MAE_dp_Pa']:.4f} "
                f"| {m['loo_R2_dp_Pa']:.4f} | {m['loo_MAE_dp_Pa']:.4f} |"]
        if "speedup" in m:
            out.append(f"\nCFD {m['cfd_wall_time_s_mean']:.0f} s per case vs "
                       f"{1e3 * m['surrogate_inference_s']:.3f} ms per prediction: speed-up {m['speedup']:.0f}x.")
        out.append("")
    else:
        out.append("## Surrogate\nnot available (run `./run_all.sh ml`)\n")

    (R / "RESULTS.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
